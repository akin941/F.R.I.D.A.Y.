#!/bin/sh
# Writes random secrets into deploy/docker/.env (gitignored) for the dev
# stack (`make secrets`, also run by `make up`). Idempotent and additive:
# a key already present in the file is NEVER overwritten -- only missing
# keys are appended -- so re-running it is always safe and an owner's own
# overrides (NVIDIA_*, OBSIDIAN_VAULT_HOST_PATH, ...) are never touched.
set -eu

ENV_FILE="${1:-deploy/docker/.env}"

random_hex() {
    # $1 = number of random bytes
    python3 -c "import secrets, sys; print(secrets.token_hex(int(sys.argv[1])))" "$1"
}

random_b64() {
    # $1 = number of random bytes, standard base64 with padding
    python3 -c "import base64, secrets, sys; print(base64.b64encode(secrets.token_bytes(int(sys.argv[1]))).decode())" "$1"
}

has_key() {
    [ -f "$ENV_FILE" ] && grep -Eq "^$1=" "$ENV_FILE"
}

append() {
    printf '%s=%s\n' "$1" "$2" >>"$ENV_FILE"
    echo "secrets: wrote $1 to $ENV_FILE"
}

if [ ! -f "$ENV_FILE" ]; then
    umask 077
    {
        echo "# Generated by \`make secrets\` -- never commit. See .env.example next to"
        echo "# this file for every supported key. Existing keys are never overwritten."
    } >"$ENV_FILE"
fi

has_key DJANGO_SECRET_KEY || append DJANGO_SECRET_KEY "$(random_hex 32)"
has_key REDIS_PASSWORD || append REDIS_PASSWORD "$(random_hex 24)"
# BFF <-> Django shared secret (Phase 4 branch 2): lets the daily stack's
# frontend container state the browser's IP (LAN gating for PIN pairing).
# An install from before the Jarvis -> Friday rename (2026-11-20) has the
# value under the legacy JARVIS_ name: carry it over so the BFF and Django
# keep agreeing (docs/runbooks/rename-jarvis-to-friday.md).
if ! has_key FRIDAY_BFF_SHARED_SECRET && has_key JARVIS_BFF_SHARED_SECRET; then
    append FRIDAY_BFF_SHARED_SECRET "$(sed -n 's/^JARVIS_BFF_SHARED_SECRET=//p' "$ENV_FILE" | tail -n 1)"
fi
has_key FRIDAY_BFF_SHARED_SECRET || append FRIDAY_BFF_SHARED_SECRET "$(random_hex 32)"
# Friday Node signing key (Phase 9 brief D4): an Ed25519 private key as
# base64 of its raw 32 bytes (any 32 random bytes are a valid RFC 8032
# seed). Signs every node `invoke`; nodes pin its public half at pairing, so
# replacing it means re-pairing every node (docs/runbooks, Phase 9).
has_key NODE_SIGNING_KEY || append NODE_SIGNING_KEY "$(random_b64 32)"

if ! has_key POSTGRES_PASSWORD; then
    # POSTGRES_PASSWORD only takes effect when the data volume is first
    # initialized. A stack created before this script existed keeps the
    # old committed password inside its volume, so a fresh random value
    # here would lock web/worker out of their own database. Keep the old
    # value for an existing volume and say how to rotate it.
    if command -v docker >/dev/null 2>&1 \
        && docker volume inspect jarvis-os_postgres-data >/dev/null 2>&1; then
        # Legacy volume, user and default password from before the rename
        # (2026-11-20): the volume name is pinned in compose.yml.
        append POSTGRES_PASSWORD jarvis
        cat >&2 <<'EOF'
secrets: WARNING -- an existing Postgres volume (jarvis-os_postgres-data)
  was initialized with the old default password; POSTGRES_PASSWORD=jarvis
  was written so the stack keeps working. Rotate it (Postgres is bound to
  127.0.0.1 only, but the default is public knowledge):
    NEW=$(python3 -c "import secrets; print(secrets.token_hex(24))")
    docker compose -f deploy/docker/compose.yml exec postgres \
      psql -U jarvis -d jarvis -c "ALTER USER jarvis PASSWORD '$NEW'"
    then set POSTGRES_PASSWORD=$NEW in deploy/docker/.env and `make up`.
EOF
    else
        append POSTGRES_PASSWORD "$(random_hex 24)"
    fi
fi
