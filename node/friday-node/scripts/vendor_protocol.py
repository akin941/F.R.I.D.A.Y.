#!/usr/bin/env python3
"""Vendor the protocol files the Swift node needs at run time.

The node validates every frame against `backend/nodes/protocol/schemas/` and
advertises the server's capability contracts (`backend/nodes/capabilities/`)
as its own catalogue (Phase 9 brief D5, D7). Those files are the single
source of truth; the app cannot read the repo at run time, so this script
copies them byte for byte into a generated Swift file (base64, so no
escaping can change a byte). `NodeCoreTests/VendoredProtocolTests` fails
when the copy drifts from the repo: rerun this script and commit the result.

    python3 node/friday-node/scripts/vendor_protocol.py          # write
    python3 node/friday-node/scripts/vendor_protocol.py --check  # CI-style

Standard library only.
"""

import argparse
import base64
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
NODES = REPO / "backend" / "nodes"
OUTPUT = REPO / "node" / "friday-node" / "Sources" / "NodeCore" / "Generated" / "VendoredProtocol.swift"
GLOBS = (
    "protocol/schemas/v1/*.schema.json",
    "capabilities/v1/*.json",
)


def render() -> str:
    paths = sorted({path for pattern in GLOBS for path in NODES.glob(pattern)})
    lines = [
        "// Generated by node/friday-node/scripts/vendor_protocol.py -- do not edit.",
        "// Byte-for-byte copies (base64) of backend/nodes protocol schemas and",
        "// capability contracts; VendoredProtocolTests checks them against the repo.",
        "",
        "enum VendoredProtocol {",
        "    static let files: [String: String] = [",
    ]
    for path in paths:
        relative = path.relative_to(NODES).as_posix()
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        lines.append(f'        "{relative}": "{encoded}",')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(REPO)} is out of date; run {Path(__file__).name}")
            return 1
        print("vendored protocol files are current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
