#!/usr/bin/env python3
"""Vendor the protocol files the Swift node needs at run time.

The node validates every frame against `backend/nodes/protocol/schemas/` and
advertises the server's capability contracts (`backend/nodes/capabilities/`)
as its own catalogue (Phase 9 brief D5, D7; v2 and the action contracts and
recipes since Phase 10 M1). Those files are the single
source of truth; the app cannot read the repo at run time, so this script
copies them byte for byte into a generated Swift file (base64, so no
escaping can change a byte). `NodeCoreTests/VendoredProtocolTests` fails
when the copy drifts from the repo: rerun this script and commit the result.

Phase 11 M1 (runbook B7): the voice host validates every `friday-voice/v1`
frame against `node/friday-voice/friday_voice/protocol/schemas/v1/`, and
refuses an installed voice child whose `uv.lock` differs from this
checkout's; both go into a second generated file,
`Generated/VendoredVoiceProtocol.swift` (the schemas byte for byte, the
lock's sha256). `VoiceProtocolTests` checks it against the repo too.

    python3 node/friday-node/scripts/vendor_protocol.py          # write
    python3 node/friday-node/scripts/vendor_protocol.py --check  # CI-style

Standard library only.
"""

import argparse
import base64
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
NODES = REPO / "backend" / "nodes"
OUTPUT = REPO / "node/friday-node/Sources/NodeCore/Generated/VendoredProtocol.swift"
VOICE = REPO / "node" / "friday-voice"
VOICE_PROTOCOL = VOICE / "friday_voice" / "protocol"
VOICE_OUTPUT = REPO / "node/friday-node/Sources/NodeCore/Generated/VendoredVoiceProtocol.swift"
VOICE_GLOBS = ("schemas/v1/host_to_child/*.schema.json", "schemas/v1/child_to_host/*.schema.json")
GLOBS = (
    "protocol/schemas/v1/*.schema.json",
    "capabilities/v1/*.json",
    # Phase 10 M1 (runbook B5): the v2 message schemas (and the `grant`
    # sub-schema), the action contracts and the recipe catalogue.
    "protocol/schemas/v2/*.schema.json",
    "capabilities/v2/*.json",
    "capabilities/v2/recipes/*.json",
)


def render() -> str:
    paths = sorted({path for pattern in GLOBS for path in NODES.glob(pattern)})
    lines = [
        "// Generated by node/friday-node/scripts/vendor_protocol.py -- do not edit.",
        "// Byte-for-byte copies (base64) of backend/nodes protocol schemas and",
        "// capability contracts; VendoredProtocolTests checks them against the repo.",
        "",
        "enum VendoredProtocol {",
        "    static let files: [String: String] = [",
    ]
    for path in paths:
        relative = path.relative_to(NODES).as_posix()
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        lines.append(f'        "{relative}": "{encoded}",')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def render_voice() -> str:
    paths = sorted({path for pattern in VOICE_GLOBS for path in VOICE_PROTOCOL.glob(pattern)})
    lock = hashlib.sha256((VOICE / "uv.lock").read_bytes()).hexdigest()
    lines = [
        "// Generated by node/friday-node/scripts/vendor_protocol.py -- do not edit.",
        "// Byte-for-byte copies (base64) of node/friday-voice/friday_voice/protocol",
        "// schemas, and the sha256 of node/friday-voice/uv.lock; VoiceProtocolTests",
        "// checks them against the repo.",
        "",
        "enum VendoredVoiceProtocol {",
        f'    static let uvLockSHA256 = "{lock}"',
        "    static let files: [String: String] = [",
    ]
    for path in paths:
        relative = path.relative_to(VOICE_PROTOCOL).as_posix()
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        lines.append(f'        "{relative}": "{encoded}",')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = ((OUTPUT, render()), (VOICE_OUTPUT, render_voice()))
    if args.check:
        stale = False
        for output, text in outputs:
            current = output.read_text(encoding="utf-8") if output.exists() else ""
            if current != text:
                print(f"{output.relative_to(REPO)} is out of date; run {Path(__file__).name}")
                stale = True
        if stale:
            return 1
        print("vendored protocol files are current")
        return 0
    for output, text in outputs:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8")
        print(f"wrote {output.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
