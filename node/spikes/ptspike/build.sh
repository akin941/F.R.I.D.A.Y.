#!/usr/bin/env bash
# Build, sign and inspect the PTSpike app (runbook mac-session-handoff A1.1–A1.3).
#
#   FRIDAY_NODE_TEAM_ID=<Personal Team ID> ./build.sh <CFBundleVersion> [--install]
#
# Signing is Xcode automatic signing for the Personal Team with hardened runtime,
# exactly the shipped path; the result is never re-signed with the source
# entitlements file. Everything this writes lives under ~/FridaySpike (mode 0700),
# outside the repo. The Team ID comes only from the environment and the identity
# only from the login Keychain: neither is ever written into the repo.
set -euo pipefail

usage() { echo "usage: FRIDAY_NODE_TEAM_ID=<team id> $0 <CFBundleVersion> [--install]" >&2; exit 2; }

[[ $# -ge 1 && $1 =~ ^[0-9]+$ ]] || usage
BUILD_NUMBER=$1
INSTALL=0
if [[ $# -ge 2 ]]; then
  [[ $2 == --install ]] || usage
  INSTALL=1
fi
: "${FRIDAY_NODE_TEAM_ID:?set FRIDAY_NODE_TEAM_ID (the Personal Team ID from A1.0; never commit it)}"

HERE=$(cd "$(dirname "$0")" && pwd)
SPIKE_HOME="${FRIDAY_SPIKE_HOME:-$HOME/FridaySpike}"
mkdir -p "$SPIKE_HOME"
chmod 700 "$SPIKE_HOME"

# A spike-only bundle id, never friday-node's. A Personal Team must register a
# globally unique App ID, so a random suffix is generated once and kept locally.
if [[ -n ${FRIDAY_NODE_SPIKE_BUNDLE_ID:-} ]]; then
  BUNDLE_ID=$FRIDAY_NODE_SPIKE_BUNDLE_ID
elif [[ -s $SPIKE_HOME/bundle-id ]]; then
  BUNDLE_ID=$(cat "$SPIKE_HOME/bundle-id")
else
  BUNDLE_ID="dev.friday.friday-node-spike.s$(openssl rand -hex 4)"
  echo "$BUNDLE_ID" > "$SPIKE_HOME/bundle-id"
fi
[[ $BUNDLE_ID == *friday-node-spike* ]] || { echo "refusing: bundle id must be a spike id" >&2; exit 1; }

# A visible string that differs per build, so build N+1 really is a different binary.
cat > "$HERE/PTSpike/BuildMarker.swift" <<EOF
// Generated by build.sh — not committed.
let buildMarker = "build $BUILD_NUMBER @ $(date -u +%Y-%m-%dT%H:%M:%SZ)"
EOF

DERIVED="$SPIKE_HOME/build"
xcodebuild -project "$HERE/PTSpike.xcodeproj" -scheme PTSpike -configuration Release \
  -derivedDataPath "$DERIVED" -allowProvisioningUpdates -allowProvisioningDeviceRegistration \
  CODE_SIGN_STYLE=Automatic DEVELOPMENT_TEAM="$FRIDAY_NODE_TEAM_ID" ENABLE_HARDENED_RUNTIME=YES \
  PRODUCT_BUNDLE_IDENTIFIER="$BUNDLE_ID" CURRENT_PROJECT_VERSION="$BUILD_NUMBER" \
  build | tail -n 5

APP="$DERIVED/Build/Products/Release/PTSpike.app"
REPORT="$SPIKE_HOME/inspect-$BUILD_NUMBER.txt"
{
  echo "== codesign --verify --strict"
  codesign --verify --strict --verbose=2 "$APP" 2>&1
  echo "== codesign -dv"
  codesign -dv --verbose=4 "$APP" 2>&1 | grep -E "Identifier|Authority|TeamIdentifier|flags|Runtime" || true
  echo "== entitlements"
  codesign -d --entitlements - --xml "$APP" 2>/dev/null | plutil -p - || true
  echo "== designated requirement"
  codesign -d -r- "$APP" 2>&1 | sed -n 's/^designated => //p'
  echo "== embedded provisioning profile"
  if [[ -f $APP/Contents/embedded.provisionprofile ]]; then
    security cms -D -i "$APP/Contents/embedded.provisionprofile" 2>/dev/null \
      | plutil -p - | grep -E '"(Name|ExpirationDate|CreationDate|TeamIdentifier)"' -A1 || true
  else
    echo "none"
  fi
  echo "== Gatekeeper (record only; rejection is expected for a local build)"
  spctl --assess --type execute -vv "$APP" 2>&1 || true
  xattr -p com.apple.quarantine "$APP" 2>&1 || true
} > "$REPORT"
cat "$REPORT"

DR=$(codesign -d -r- "$APP" 2>&1 | sed -n 's/^designated => //p')
if [[ $DR == *cdhash* || -z $DR ]]; then
  echo "FAIL: designated requirement is ad-hoc or missing — fix the signing" >&2
  exit 1
fi
SAVED="$SPIKE_HOME/designated-requirement.txt"
if [[ -s $SAVED ]]; then
  if [[ $DR == "$(cat "$SAVED")" ]]; then
    echo "designated requirement: EQUAL to the saved one"
  else
    echo "designated requirement: DIFFERS from $SAVED" >&2
    exit 1
  fi
else
  echo "$DR" > "$SAVED"
  echo "designated requirement saved to $SAVED"
fi

if [[ $INSTALL -eq 1 ]]; then
  pkill -x PTSpike 2>/dev/null && sleep 1 || true
  ditto "$APP" /Applications/PTSpike.app
  open /Applications/PTSpike.app
  echo "installed and launched build $BUILD_NUMBER; status: $SPIKE_HOME/status-$BUILD_NUMBER.txt"
fi
