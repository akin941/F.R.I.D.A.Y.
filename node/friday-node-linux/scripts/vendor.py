"""Vendor (or `--check`) the backend's node-side code into
`friday_node_linux/_vendor/` (Phase 13 brief D10).

`friday-node-linux` must not import the backend, yet the Python reference
node (`backend/nodes/reference/`) is the single executable spec of the node
side of the Friday Node protocol. So the reference node, the protocol and
the capability contracts are **copied**, never re-implemented:

- every file in `SOURCES` is copied from `backend/` to
  `friday_node_linux/_vendor/<same relative path>`;
- a Python file gets a one-line generated header and its absolute imports
  of `nodes.` / `integrations.` are rewritten to
  `friday_node_linux._vendor.nodes.` / `..._vendor.integrations.` (only
  `from`/`import` statements at the start of a line; nothing else changes);
- data files (JSON schemas, contracts, fixtures) are copied byte for byte;
- package `__init__.py` files that are not themselves vendored are generated
  empty (the backend's `nodes/__init__.py` is a Django app's);
- `vendor.lock` records, per file, the sha256 of the backend source and of
  the vendored copy.

`--check` (CI, `make linux-node-test`, the closeout's `linux_node_vendor`
preflight row) re-renders everything from the backend and fails when a
vendored file, the lock, or the set of files differs: the reference node
stays the one spec and the Linux node cannot diverge silently.

Run from `node/friday-node-linux/`:

    uv run python scripts/vendor.py           # after a backend change
    uv run python scripts/vendor.py --check   # CI

Reads and writes text only -- it never imports the backend.
"""

import hashlib
import re
import sys
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = PACKAGE_ROOT.parents[1]
BACKEND = REPO_ROOT / "backend"
VENDOR = PACKAGE_ROOT / "friday_node_linux" / "_vendor"
LOCK = PACKAGE_ROOT / "vendor.lock"
VENDOR_PACKAGE = "friday_node_linux._vendor"

# Whole trees (every file except caches) and single files, relative to
# backend/. The reference node's own imports reach confirm, executor,
# sandbox, stream_scrub, verifier_v2 and worktree, so they are vendored too
# (the session state machine is one module; v2 paths stay unreachable on
# the Linux node's v1-only session). `fixtures/` and the conformance keys
# serve `friday-node-linux conformance` only.
TREES = (
    "nodes/protocol",
    "nodes/capabilities",
    "nodes/reference/fixtures",
    "integrations/node_reference/contracts",
)
FILES = (
    "nodes/reference/__init__.py",
    "nodes/reference/_scrubber_vendored.py",
    "nodes/reference/confirm.py",
    "nodes/reference/executor.py",
    "nodes/reference/hook_relay.py",
    "nodes/reference/local_policy.py",
    "nodes/reference/node.py",
    "nodes/reference/readers.py",
    "nodes/reference/sandbox.py",
    "nodes/reference/spool.py",
    "nodes/reference/stream_scrub.py",
    "nodes/reference/transport.py",
    "nodes/reference/verifier_v2.py",
    "nodes/reference/worktree.py",
    "nodes/conformance/keys/conformance_keys.json",
    "integrations/node_reference/__init__.py",
    "integrations/node_reference/owner_turns.py",
    "integrations/cli/_scrubber_vendored.py",
)
# Generated (empty) package markers: these backend `__init__`s are not
# vendored (Django app / CLI packages).
GENERATED_INITS = (
    "__init__.py",
    "nodes/__init__.py",
    "nodes/conformance/__init__.py",
    "integrations/__init__.py",
    "integrations/cli/__init__.py",
)
SKIP_PARTS = {"__pycache__", ".pytest_cache"}
# The conformance node id is a constant in both places (the cases module is
# not vendored: it needs the private test keys to sign).
CASES = BACKEND / "nodes" / "conformance" / "cases.py"
CONFORMANCE = PACKAGE_ROOT / "friday_node_linux" / "conformance.py"
_BACKEND_NODE_ID = re.compile(r'^NODE_ID = "([0-9a-f-]{36})"$', re.M)
_LINUX_NODE_ID = re.compile(r'^CONFORMANCE_NODE_ID = "([0-9a-f-]{36})"$', re.M)

_IMPORT = re.compile(
    r"^(?P<indent>[ \t]*)(?P<kw>from|import)[ \t]+(?P<pkg>nodes|integrations)\.", re.M
)
PY_HEADER = "# GENERATED by scripts/vendor.py from backend/{path} -- do not edit.\n"
INIT_TEXT = '"""Generated by scripts/vendor.py: a package of vendored backend code."""\n'
LOCK_HEADER = (
    "# friday-node-linux vendor lock -- generated by `uv run python scripts/vendor.py`,\n"
    "# checked by `--check` (CI) and by the closeout's `linux_node_vendor` preflight row.\n"
    "# <sha256 of backend source>  <sha256 of vendored copy>  <path relative to backend/>\n"
)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_files() -> list:
    """Every vendored source path, relative to backend/, sorted."""
    paths = set(FILES)
    for tree in TREES:
        for path in (BACKEND / tree).rglob("*"):
            if path.is_file() and not SKIP_PARTS & set(path.parts) and path.suffix != ".pyc":
                paths.add(path.relative_to(BACKEND).as_posix())
    return sorted(paths)


def node_id(path, pattern):
    match = pattern.search(path.read_text(encoding="utf-8")) if path.exists() else None
    return match.group(1) if match else None


def rewrite(text: str) -> str:
    return _IMPORT.sub(lambda m: f"{m['indent']}{m['kw']} {VENDOR_PACKAGE}.{m['pkg']}.", text)


def render(relative: str) -> bytes:
    raw = (BACKEND / relative).read_bytes()
    if relative.endswith(".py"):
        text = raw.decode("utf-8")
        return (PY_HEADER.format(path=relative) + rewrite(text)).encode("utf-8")
    return raw


def expected() -> tuple:
    """`({relative vendored path: bytes}, lock text)`."""
    files = {}
    lock = [LOCK_HEADER]
    for relative in source_files():
        source = (BACKEND / relative).read_bytes()
        body = render(relative)
        files[relative] = body
        lock.append(f"{sha256(source)}  {sha256(body)}  {relative}\n")
    for relative in GENERATED_INITS:
        files.setdefault(relative, INIT_TEXT.encode("utf-8"))
    return files, "".join(lock)


def current_files() -> dict:
    if not VENDOR.is_dir():
        return {}
    out = {}
    for path in VENDOR.rglob("*"):
        if path.is_file() and not SKIP_PARTS & set(path.parts) and path.suffix != ".pyc":
            out[path.relative_to(VENDOR).as_posix()] = path.read_bytes()
    return out


def check() -> list:
    """The drift found (empty when the vendored tree matches the backend)."""
    files, lock = expected()
    have = current_files()
    problems = []
    for relative in sorted(set(files) | set(have)):
        if relative not in have:
            problems.append(f"missing: {relative}")
        elif relative not in files:
            problems.append(f"not a vendored file: {relative}")
        elif have[relative] != files[relative]:
            problems.append(f"differs from backend/{relative}")
    if not LOCK.exists() or LOCK.read_text(encoding="utf-8") != lock:
        problems.append("vendor.lock is stale")
    if node_id(CASES, _BACKEND_NODE_ID) != node_id(CONFORMANCE, _LINUX_NODE_ID):
        problems.append("conformance.py CONFORMANCE_NODE_ID differs from the cases' NODE_ID")
    return problems


def write() -> None:
    files, lock = expected()
    for relative, body in files.items():
        target = VENDOR / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(body)
    for relative in set(current_files()) - set(files):
        (VENDOR / relative).unlink()
    LOCK.write_text(lock, encoding="utf-8")


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--check" in argv:
        problems = check()
        for problem in problems:
            print(problem)
        if problems:
            print("friday_node_linux/_vendor is stale: run `uv run python scripts/vendor.py`.")
            return 1
        return 0
    write()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
