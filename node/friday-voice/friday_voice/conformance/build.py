"""Render the conformance cases and frame vectors to JSON, or `--check`
them (the `build_node_conformance --check` pattern, brief D6).

    friday-voice conformance --build   # write the files
    friday-voice conformance --check   # regenerate nothing; fail on drift

The files are what the Swift host's test target loads, so a definition
change without a rebuild, or a hand edit of a JSON file, fails CI.

`conformance.lock` (Phase 11 closeout, brief §8) sits next to
`pyproject.toml`: the sha256 of every case file, the frame vectors and the
frozen `friday-voice/v1` schemas, as `<sha256>  <path>` lines with paths
relative to `node/friday-voice`. It is generated with the files and checked
with them; the server's `friday_voice_conformance` preflight check reads it
with nothing but hashlib (the backend imports nothing from this package),
so a hand-edited case, vector or schema file shows up there too.
"""

import hashlib
import json
from pathlib import Path

from .definitions import child_cases, frame_vectors, host_cases

PACKAGE_DIR = Path(__file__).resolve().parents[1]
CASES_DIR = PACKAGE_DIR / "conformance" / "cases"
VECTORS_FILE = PACKAGE_DIR / "protocol" / "vectors" / "frames.json"
SCHEMAS_DIR = PACKAGE_DIR / "protocol" / "schemas" / "v1"
LOCK_NAME = "conformance.lock"
LOCK_HEADER = (
    "# friday-voice/v1 conformance lock -- generated by `friday-voice conformance --build`,\n"
    "# checked by `--check` and by the server's `friday_voice_conformance` preflight check.\n"
    "# <sha256>  <path relative to node/friday-voice>\n"
)
# The paths the lock names are fixed strings (not derived from the
# directories above, which tests redirect), so the lock depends on content.
_CASES_REL = "friday_voice/conformance/cases"
_VECTORS_REL = "friday_voice/protocol/vectors/frames.json"
_SCHEMAS_REL = "friday_voice/protocol/schemas/v1"


def lock_file() -> Path:
    return PACKAGE_DIR.parent / LOCK_NAME


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render_lock(cases_text: dict, vectors_text: str) -> str:
    """The lock over the rendered case files (`{"<family>/<id>.json":
    text}`), the rendered frame vectors and the schema files on disk."""
    entries = {_VECTORS_REL: _sha256(vectors_text.encode("utf-8"))}
    for rel, text in cases_text.items():
        entries[f"{_CASES_REL}/{rel}"] = _sha256(text.encode("utf-8"))
    for schema in sorted(SCHEMAS_DIR.glob("*/*.schema.json")):
        rel = schema.relative_to(SCHEMAS_DIR).as_posix()
        entries[f"{_SCHEMAS_REL}/{rel}"] = _sha256(schema.read_bytes())
    lines = [f"{digest}  {path}" for path, digest in sorted(entries.items())]
    return LOCK_HEADER + "\n".join(lines) + "\n"


def _dump(value) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def render() -> dict:
    """{absolute path: file text} for every generated file."""
    vectors = _dump(frame_vectors())
    files = {VECTORS_FILE: vectors}
    cases_text = {}
    for family, cases in (("host", host_cases()), ("child", child_cases())):
        ids = [case["id"] for case in cases]
        if len(set(ids)) != len(ids):
            raise ValueError(f"duplicate {family} case id")
        for case in cases:
            text = _dump(case)
            files[CASES_DIR / family / f"{case['id']}.json"] = text
            cases_text[f"{family}/{case['id']}.json"] = text
    files[lock_file()] = render_lock(cases_text, vectors)
    return files


def _on_disk() -> set:
    found = set(CASES_DIR.glob("*/*.json"))
    if VECTORS_FILE.exists():
        found.add(VECTORS_FILE)
    return found


def write() -> list:
    files = render()
    for stale in _on_disk() - set(files):
        stale.unlink()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return sorted(files)


def check() -> list:
    """The relative paths that drifted (changed, missing or unexpected)."""
    files = render()
    drift = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            drift.append(path)
    drift += sorted(_on_disk() - set(files))
    return [str(path.relative_to(PACKAGE_DIR.parent)) for path in drift]


def load_cases(family, cases_dir=None) -> list:
    """The case files of one family, as the Swift test target reads them."""
    root = Path(cases_dir) if cases_dir else CASES_DIR
    return [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted((root / family).glob("*.json"))
    ]
