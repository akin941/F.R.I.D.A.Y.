#!/usr/bin/env python3
"""Builds the driver's protocol snapshot from the JSON Schemas the pinned
Codex binary generates (Phase 10 brief D10 "Pins and contract tests").

Usage (run by generate_driver_schemas.sh, never by the app):

    codex_schema_subset.py <generated-schema-dir> <version> <out protocol.json>

Input: the directory written by `codex app-server generate-json-schema
--out <dir>` -- the four message unions (ClientRequest, ClientNotification,
ServerRequest, ServerNotification) as `oneOf` lists whose entries carry a
`method` (enum/const) and a `params` schema, plus one schema per response
type. Output: `friday-codex-app-server-subset/v1`, the format
`harness.drivers.schema.ProtocolSnapshot` reads, with `"provisional": false`.

Stdlib only; it imports nothing of Friday's. If the generated layout of a
future version differs, this script fails loudly rather than writing a
partial snapshot: the contract test (`harness/tests/test_driver_contract.py`)
must pass against whatever it writes before the pin bump merges.
"""

import json
import sys
from pathlib import Path

UNIONS = {
    "client_requests": "ClientRequest",
    "client_notifications": "ClientNotification",
    "server_requests": "ServerRequest",
    "server_notifications": "ServerNotification",
}


def _load(directory, name):
    for candidate in (directory / f"{name}.json", directory / "v2" / f"{name}.json"):
        if candidate.is_file():
            return json.loads(candidate.read_text(encoding="utf-8"))
    raise SystemExit(f"generated schema {name}.json not found under {directory}")


def _method(entry):
    method = (entry.get("properties") or {}).get("method") or {}
    if "const" in method:
        return method["const"]
    values = method.get("enum") or []
    if len(values) != 1:
        raise SystemExit(f"cannot read the method of union entry {entry!r:.200}")
    return values[0]


def _response_name(params_schema):
    ref = (params_schema or {}).get("$ref", "")
    name = ref.rsplit("/", 1)[-1]
    if name.endswith("Params"):
        return name[: -len("Params")] + "Response"
    return ""


def main(argv):
    if len(argv) != 4:
        raise SystemExit(__doc__)
    directory, version, out = Path(argv[1]), argv[2], Path(argv[3])
    definitions = {}
    document = {
        "schema_format": "friday-codex-app-server-subset/v1",
        "version": version,
        "provisional": False,
        "source": f"generated by codex app-server generate-json-schema ({version})",
        "wire": {"framing": "jsonl", "jsonrpc_field": "omitted"},
    }
    for key, union_name in UNIONS.items():
        union = _load(directory, union_name)
        definitions.update(union.get("definitions") or {})
        entries = {}
        for entry in union.get("oneOf") or []:
            method = _method(entry)
            params = (entry.get("properties") or {}).get("params") or {"type": ["object", "null"]}
            entries[method] = {"params": params}
            if key in ("client_requests", "server_requests"):
                response = _response_name(params)
                if response:
                    try:
                        schema = _load(directory, response)
                    except SystemExit:
                        schema = None
                    if schema is not None:
                        definitions.update(schema.pop("definitions", {}) or {})
                        entries[method]["result"] = schema
        if not entries:
            raise SystemExit(f"{union_name}.json lists no methods")
        document[key] = entries
    document["definitions"] = definitions
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv)
